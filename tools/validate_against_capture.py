#!/usr/bin/env python3
"""Validate a camera recipe against real captures from a physical camera.

Inputs (see docs/REAL_CAMERA_VALIDATION.md for the capture protocol and the
``capture.yaml`` layout):

* dark and flat-field raw stacks  -> EMVA 1288 photon-transfer parameters
  (K, read noise, DSNU, PRNU, dark current, saturation capacity);
* a ColorChecker raw              -> per-patch electrons and colour error;
* a slanted-edge raw              -> ISO 12233 SFR / MTF.

For each measurement the matching simulation is run with the recipe (same
signal levels, exposure times, frame counts and ROI sizes), and measured,
recipe and simulated values are reported side by side. Comparing measured
against *simulated* (not just against the recipe numbers) removes estimator
bias shared by both -- finite frame counts, quantisation, the EMVA definition
of saturation at the variance peak.

``synthesize`` writes a complete capture set generated by the simulator itself
(tools/apply_emva_noise.py), so the harness can be round-trip tested without a
camera. Real captures are needed for an actual validation.

References: EMVA Standard 1288, Release 4.0 (2021), *Standard for
Characterization of Image Sensors and Cameras* (photon transfer, sections on
temporal noise, saturation, dark current, DSNU1288/PRNU1288); ISO 12233:2017 /
2023 (slanted-edge SFR); CIE 15:2018 / CIEDE2000 (colour difference).

Examples::

    venv/bin/python tools/validate_against_capture.py synthesize \\
        --recipe config/camera_recipes/default.yaml --out-dir out/capture_synth
    venv/bin/python tools/validate_against_capture.py validate \\
        --capture out/capture_synth/capture.yaml --out-dir out/capture_synth/report --plot
"""

