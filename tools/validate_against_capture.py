def _fmt(v: object) -> str:
    if v is None:
        return "n/a"
    if isinstance(v, float):
        return f"{v:.4g}"
    return str(v)


def markdown_report(report: dict) -> str:
    lines = [f"# Capture validation: {report['recipe']}", ""]
    if report.get("synthetic"):
        lines += ["**Synthetic capture (simulator round trip) -- not a real-camera validation.**", ""]
    if "emva" in report:
        lines += [
            f"## EMVA 1288 ({report['emva']['plane']} plane)",
            "",
            "| parameter | measured | recipe | simulated | meas vs recipe % | meas vs sim % |",
            "|---|---|---|---|---|---|",
        ]
        for k, r in report["emva"]["parameters"].items():
            vals = [r["measured"], r["recipe"], r["simulated"], r["measured_vs_recipe_pct"]]
            lines.append(
                f"| {k} | " + " | ".join(_fmt(v) for v in vals) + f" | {_fmt(r['measured_vs_simulated_pct'])} |"
            )
        lines.append("")
    if "colorchecker" in report:
        c = report["colorchecker"]
        lines += [
            "## ColorChecker",
            "",
            f"CIEDE2000 measured vs simulated: mean {c['delta_e_2000_mean']:.2f}, max {c['delta_e_2000_max']:.2f}; "
            f"RMS white-normalised R/B error {c['rms_white_normalised_error_pct']:.2f} %",
            "",
            "| # | patch | meas e- (R,G,B) | sim e- (R,G,B) | err % (R,G,B) | dE00 |",
            "|---|---|---|---|---|---|",
        ]
        for pt in c["patches"]:
            fm = lambda a, f: ", ".join(f.format(v) for v in a)  # noqa: E731
            lines.append(
                f"| {pt['index']} | {pt['name']} | {fm(pt['measured_e_rgb'], '{:.0f}')} | "
                f"{fm(pt['simulated_e_rgb'], '{:.0f}')} | {fm(pt['white_normalised_error_pct_rgb'], '{:+.1f}')} | "
                f"{pt['delta_e_2000']:.2f} |"
            )
        lines.append("")
    if "slanted_edge" in report:
        e = report["slanted_edge"]
        lines += [
            f"## Slanted edge ({e['plane']} plane, simulation: {e['simulation']})",
            "",
            f"- edge angle: measured {e['measured']['angle_deg']:.3f} deg",
            f"- MTF50: measured {e['mtf50_measured_cy_per_px']:.4f} cy/px ({e['mtf50_measured_lp_per_mm']:.1f} lp/mm), "
            f"simulated {e['mtf50_simulated_cy_per_px']:.4f} cy/px ({e['mtf50_simulated_lp_per_mm']:.1f} lp/mm), "
            f"{_fmt(e['mtf50_measured_vs_simulated_pct'])} %",
            f"- RMS MTF difference up to plane Nyquist: {e['mtf_rms_difference_to_plane_nyquist']:.4f}",
            "",
        ]
    return "\n".join(lines)


