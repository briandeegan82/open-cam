# Raw I/O and CFA handling
# =====================================================================
def read_raw(path: Path, fmt: dict) -> tuple[np.ndarray, dict]:
    """Read one raw frame as float DN, plus any metadata found in the file.

    ``raw16``: headerless little-endian uint16 (what apply_emva_noise writes),
    shape from ``fmt["height"]``/``fmt["width"]``. ``npy``: a 2-D array.
    ``dng`` (or any LibRaw format): via the optional ``rawpy`` package; black
    level, white level and CFA pattern are taken from the file.
    """
    path = Path(path)
    kind = str(fmt.get("format") or path.suffix.lstrip(".")).lower()
    meta: dict = {}
    if kind == "raw16":
        h, w = int(fmt["height"]), int(fmt["width"])
        data = np.fromfile(path, dtype="<u2")
        if data.size != h * w:
            raise ValueError(f"{path}: {data.size} samples, expected {h}x{w}={h * w}")
        return data.reshape(h, w).astype(np.float64), meta
    if kind == "npy":
        return np.asarray(np.load(path), dtype=np.float64), meta
    try:
        import rawpy  # noqa: PLC0415
    except ImportError as exc:  # pragma: no cover - optional dependency
        raise ImportError(f"reading {path} ({kind}) needs the optional 'rawpy' package: pip install rawpy") from exc
    with rawpy.imread(str(path)) as raw:  # pragma: no cover - needs real DNGs
        img = raw.raw_image_visible.astype(np.float64)
        meta["black_level_DN"] = float(np.mean(raw.black_level_per_channel))
        meta["white_level_DN"] = float(raw.white_level)
        desc = raw.color_desc.decode()
        pat = raw.raw_pattern[:2, :2].ravel()
        meta["cfa_pattern"] = "".join(desc[i] for i in pat).replace("G", "G")
    return img, meta


def cfa_offsets(pattern: str | None) -> dict[str, list[tuple[int, int]]]:
    """(row, col) offsets of each colour inside the 2x2 CFA tile."""
    if not pattern:
        return {"R": [(0, 0)], "G": [(0, 0)], "B": [(0, 0)]}
    p = pattern.upper()
    if len(p) != 4 or sorted(p) != ["B", "G", "G", "R"]:
        raise ValueError(f"unsupported CFA pattern {pattern!r}; expected a Bayer RGGB/GRBG/GBRG/BGGR")
    out: dict[str, list[tuple[int, int]]] = {"R": [], "G": [], "B": []}
    for i, ch in enumerate(p):
        out[ch].append((i // 2, i % 2))
    return out


def cfa_plane(img: np.ndarray, pattern: str | None, colour: str = "G", index: int = 0) -> np.ndarray:
    """One colour sub-plane (half resolution for Bayer; the image itself for mono)."""
    if not pattern:
        return img
    r, c = cfa_offsets(pattern)[colour.upper()][index]
    return img[r::2, c::2]


def crop(img: np.ndarray, roi: list | None) -> np.ndarray:
    """Crop ``[x0, y0, x1, y1]``; the origin is rounded down to even to keep CFA phase."""
    if roi is None:
        return img
    x0, y0, x1, y1 = (int(v) for v in roi)
    return img[y0 - (y0 % 2) : y1, x0 - (x0 % 2) : x1]


def colour_mean(img: np.ndarray, pattern: str | None, colour: str) -> float:
    planes = [cfa_plane(img, pattern, colour, i) for i in range(len(cfa_offsets(pattern)[colour.upper()]))]
    return float(np.mean([p.mean() for p in planes]))


# =====================================================================
# Capture manifest
# =====================================================================
@dataclass
class Capture:
    root: Path
    cfg: dict

    @property
    def raw(self) -> dict:
        return self.cfg.get("raw", {}) or {}

    @property
    def pattern(self) -> str | None:
        return self.raw.get("cfa_pattern")

    def fmt(self, section: dict | None = None) -> dict:
        f = dict(self.raw)
        for k in ("format", "width", "height"):
            if section and k in section:
                f[k] = section[k]
        return f

    def files(self, spec: str | list) -> list[Path]:
        items = spec if isinstance(spec, list) else [spec]
        out: list[Path] = []
        for it in items:
            matches = sorted(glob.glob(str(self.root / it)))
            if not matches:
                raise FileNotFoundError(f"no files match {self.root / it}")
            out.extend(Path(m) for m in matches)
        return out

    def stack(self, entry: dict, roi: list | None, colour: str) -> np.ndarray:
        frames = [read_raw(p, self.fmt(entry))[0] for p in self.files(entry["frames"])]
        if len(frames) < 2:
            raise ValueError(f"EMVA stacks need >= 2 frames, got {len(frames)} for {entry['frames']}")
        return np.stack([cfa_plane(crop(f, roi), self.pattern, colour) for f in frames])


def load_capture(path: Path) -> Capture:
    path = Path(path).resolve()
    cfg = yaml.safe_load(path.read_text()) or {}
    if int(cfg.get("schema_version", SCHEMA_VERSION)) != SCHEMA_VERSION:
        raise ValueError(f"{path}: unsupported capture schema_version {cfg.get('schema_version')}")
    return Capture(root=path.parent, cfg=cfg)


def resolve_recipe(capture: Capture, override: Path | None) -> Path:
    ref = override or capture.cfg.get("camera_recipe")
    if ref is None:
        raise ValueError("no camera recipe: set camera_recipe in capture.yaml or pass --recipe")
    p = Path(ref)
    for cand in (p, REPO / p, capture.root / p):
        if cand.is_file():
            return cand.resolve()
    raise FileNotFoundError(f"camera recipe not found: {ref}")


