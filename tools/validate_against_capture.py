def patch_rois(cfg: dict) -> list[list[int]]:
    """24 patch ROIs, row-major from patch 1 (dark skin) to 24 (black)."""
    if "patch_rois" in cfg:
        rois = [list(map(int, r)) for r in cfg["patch_rois"]]
    else:
        g = cfg["grid"]
        (x0, y0), (x1, y1) = g["first_patch_centre_px"], g["last_patch_centre_px"]
        h = int(g.get("patch_half_size_px", 8))
        rois = []
        for i in range(4):
            for j in range(6):
                cx = x0 + (x1 - x0) * j / 5.0
                cy = y0 + (y1 - y0) * i / 3.0
                rois.append([round(cx - h), round(cy - h), round(cx + h), round(cy + h)])
    if len(rois) != cs.COLORCHECKER_PATCHES:
        raise ValueError(f"expected {cs.COLORCHECKER_PATCHES} patch ROIs, got {len(rois)}")
    return rois


def patch_means_dn(img: np.ndarray, pattern: str | None, rois: list, black: float) -> np.ndarray:
    return np.array([[colour_mean(crop(img, r), pattern, c) - black for c in "RGB"] for r in rois])


def spectral_patch_electrons(model: dict, illuminant: str) -> tuple[np.ndarray, np.ndarray]:
    """Relative camera electrons ``(24, 3)`` and reference XYZ (Y_white = 1)."""
    wl = SPECTRAL_GRID_NM
    chart = cs.load_colorchecker(REPO, wl)
    _, spd = cs.load_illuminant(REPO, illuminant, wl)
    q = model["sensor"]["quantum_efficiency"]
    qe = cs.load_qe_rgb(
        REPO, {"red": q["red_csv"], "green": q["green_csv"], "blue": q["blue_csv"], "ircf": q.get("ircf_csv")}, wl
    )
    rgb = cs.camera_rgb_from_spectra(wl, chart.reflectance, spd, qe, normalise=False)
    xyz = cs.xyz_from_spectra(wl, chart.reflectance, spd)
    return rgb, xyz


def chart_electron_image(patch_e: np.ndarray, patch_px: int) -> np.ndarray:
    img = np.zeros((4 * patch_px, 6 * patch_px, 3), dtype=np.float64)
    for n in range(24):
        i, j = divmod(n, 6)
        img[i * patch_px : (i + 1) * patch_px, j * patch_px : (j + 1) * patch_px] = patch_e[n]
    return img


def chart_grid_cfg(patch_px: int) -> dict:
    return {
        "first_patch_centre_px": [patch_px / 2.0, patch_px / 2.0],
        "last_patch_centre_px": [5.5 * patch_px, 3.5 * patch_px],
        "patch_half_size_px": patch_px // 4,
    }


def colorchecker_section(
    capture: Capture, recipe: Path, model: dict, rec: dict, emva: dict | None, seed: int, workdir: Path
) -> dict:
    """Per-patch electrons and colour error, measured vs simulated.

    The simulated chart is the recipe's QE x illuminant x reflectance spectra,
    scaled so the white patch's green signal equals the measured one (the
    absolute scene illuminance is not part of the capture), pushed through the
    production sensor chain. Colour error: one 3x3 matrix fitted (least squares)
    from simulated camera RGB to reference XYZ is applied to both, and CIEDE2000
    is computed between them, so it measures only the spectral-response mismatch.
    """
    cfg = capture.cfg["colorchecker"]
    black = emva["measured"]["black_level_DN"] if emva else capture.raw.get("black_level_DN", rec["black_level_DN"])
    img, meta = read_raw(capture.root / cfg["file"], capture.fmt(cfg))
    black = meta.get("black_level_DN", black)
    meas_dn = patch_means_dn(img, capture.pattern, patch_rois(cfg), black)
    k_meas = emva["measured"]["K_e_per_DN"] if emva else rec["K_e_per_DN"]

    rel_e, xyz_ref = spectral_patch_electrons(model, str(cfg.get("illuminant", "D65")))
    scale = meas_dn[WHITE_PATCH, 1] * rec["K_e_per_DN"] / rel_e[WHITE_PATCH, 1]
    patch_px = int(cfg.get("simulated_patch_px", 24))
    sim_raw = run_sensor_chain(
        recipe, chart_electron_image(rel_e * scale, patch_px), float(cfg.get("exposure_s", 0.01)), seed, workdir
    )
    sim_dn = patch_means_dn(
        sim_raw,
        model["cfa"].get("pattern") if model["cfa"].get("enabled") else None,
        patch_rois({"grid": chart_grid_cfg(patch_px)}),
        rec["black_level_DN"],
    )

    meas_n = meas_dn / meas_dn[WHITE_PATCH, 1]
    sim_n = sim_dn / sim_dn[WHITE_PATCH, 1]
    ccm, *_ = np.linalg.lstsq(sim_n, xyz_ref, rcond=None)
    white = np.ones((1, SPECTRAL_GRID_NM.size))
    _, spd = cs.load_illuminant(REPO, str(cfg.get("illuminant", "D65")), SPECTRAL_GRID_NM)
    white_xyz = cs.xyz_from_spectra(SPECTRAL_GRID_NM, white, spd)[0]
    lab_meas = cs.xyz_to_lab(meas_n @ ccm, white_xyz)
    lab_sim = cs.xyz_to_lab(sim_n @ ccm, white_xyz)
    de = cs.delta_e_2000(lab_meas, lab_sim)
    rel_err = 100.0 * (meas_n / np.maximum(sim_n, 1e-12) - 1.0)
    chroma_meas = np.stack([meas_n[:, 0] / meas_n[:, 1], meas_n[:, 2] / meas_n[:, 1]], axis=1)
    chroma_sim = np.stack([sim_n[:, 0] / sim_n[:, 1], sim_n[:, 2] / sim_n[:, 1]], axis=1)
    chart = cs.load_colorchecker(REPO, SPECTRAL_GRID_NM)
    patches = [
        {
            "index": i + 1,
            "name": chart.names[i],
            "measured_e_rgb": (meas_dn[i] * k_meas).tolist(),
            "simulated_e_rgb": (sim_dn[i] * rec["K_e_per_DN"]).tolist(),
            "white_normalised_error_pct_rgb": rel_err[i].tolist(),
            "rg_bg_ratio_error_pct": (100.0 * (chroma_meas[i] / chroma_sim[i] - 1.0)).tolist(),
            "delta_e_2000": float(de[i]),
        }
        for i in range(24)
    ]
    neutral = slice(18, 24)
    return {
        "illuminant": str(cfg.get("illuminant", "D65")),
        "black_level_DN_used": float(black),
        "white_scale_e": float(scale),
        "delta_e_2000_mean": float(np.mean(de)),
        "delta_e_2000_max": float(np.max(de)),
        "rms_white_normalised_error_pct": float(np.sqrt(np.mean(rel_err[:, [0, 2]] ** 2))),
        "neutral_channel_ratio_meas_over_sim": (meas_n[neutral].mean(0) / sim_n[neutral].mean(0)).tolist(),
        "patches": patches,
    }


