def recipe_emva(model: dict, temperature_c: float | None = None) -> dict:
    """The recipe's EMVA parameters, as apply_emva_noise would use them."""
    emva = model["noise"]["emva"]
    adc = model["noise"]["adc"]
    gain = float(emva.get("iso_gain_factor", 1.0))
    # Same ISO scaling as apply_emva_noise.iso_scaled_conversion.
    k = float(emva["overall_system_gain_K_e_per_DN"]) / gain
    fw = float(adc["full_well_e"]) / gain
    t_ref = float(emva.get("dark_current_reference_temp_c", 20.0))
    t = float(emva.get("temperature_c", t_ref)) if temperature_c is None else float(temperature_c)
    doubling = max(float(emva.get("dark_current_doubling_per_c", 6.0)), 1e-6)
    return {
        "K_e_per_DN": k,
        "read_noise_e": math.hypot(float(emva.get("sigma_d_e", 0.0)), float(emva.get("sigma_amp_e", 0.0)) * gain),
        "dsnu_e": float(emva.get("dsnu_std_e", 0.0)),
        "prnu_fraction": float(emva.get("prnu_std_fraction", 0.0)),
        "dark_current_e_per_s": float(emva.get("dark_current_e_per_s", 0.0)) * 2.0 ** ((t - t_ref) / doubling),
        "full_well_e": fw,
        "black_level_DN": float(emva.get("black_level_DN", 0.0)),
        "bit_depth": int(adc.get("bit_depth", 12)),
        "use_poisson": bool(emva.get("use_poisson_shot_noise", True)),
    }


# =====================================================================
# EMVA 1288 analysis
# =====================================================================
def _temporal(stack: np.ndarray) -> tuple[float, float]:
    s = np.asarray(stack, dtype=np.float64)
    return float(s.mean()), float(s.var(axis=0, ddof=1).mean())


def _nearest(entries: list[tuple[float, np.ndarray]], t: float) -> tuple[float, np.ndarray]:
    return min(entries, key=lambda e: abs(e[0] - t))


def analyse_emva(
    darks: list[tuple[float, np.ndarray]],
    flats: list[tuple[float, float | None, np.ndarray]],
) -> dict:
    """EMVA 1288 photon-transfer analysis.

    *darks*: ``(exposure_s, stack)``; *flats*: ``(exposure_s, relative_exposure,
    stack)``; stacks are ``(L, H, W)`` DN from a single colour plane.

    * K from the slope of ``sigma2_y - sigma2_y.dark`` vs ``mu_y - mu_y.dark``
      over 0..70 % of saturation (EMVA 1288 photon transfer method);
    * saturation capacity at the mean where the temporal variance peaks;
    * read noise ``sqrt(sigma2_y.dark - 1/12) / K`` at the shortest exposure;
    * dark current from the slope of the dark mean vs exposure time;
    * DSNU1288 / PRNU1288 with the residual-temporal-noise correction
      (tools/emva_theory.emva1288_dsnu / emva1288_prnu).
    """
    if not darks or not flats:
        raise ValueError("EMVA analysis needs at least one dark and one flat stack")
    darks = sorted(darks, key=lambda d: d[0])
    dark_stats = [(t, *_temporal(s)) for t, s in darks]
    points = []
    for idx, (t, rel, s) in enumerate(flats):
        mu, var = _temporal(s)
        _, dmu, dvar = min(dark_stats, key=lambda d: abs(d[0] - t))
        points.append(
            {"exposure_s": t, "relative_exposure": rel, "mu_dn": mu - dmu, "var_dn2": var - dvar, "stack": idx}
        )
    points.sort(key=lambda p: p["mu_dn"])
    mu = np.array([p["mu_dn"] for p in points])
    var = np.array([p["var_dn2"] for p in points])

    i_sat = int(np.argmax(var))
    saturated = i_sat < len(points) - 1
    mu_sat = float(mu[i_sat])
    sel = (mu > 0) & (mu <= K_FIT_MAX_FRACTION_OF_SAT * mu_sat)
    if sel.sum() < 2:
        raise ValueError("need >= 2 flat levels between 0 and 70 % of saturation to fit K")
    slope, intercept = np.polyfit(mu[sel], var[sel], 1)
    k_e_per_dn = 1.0 / float(slope)

    t0, dmu0, dvar0 = dark_stats[0]
    read_e = math.sqrt(max(dvar0 - QUANTISATION_VAR_DN2, 0.0)) * k_e_per_dn
    if len(dark_stats) >= 2 and dark_stats[-1][0] > dark_stats[0][0]:
        ts = np.array([d[0] for d in dark_stats])
        ms = np.array([d[1] for d in dark_stats])
        d_slope, d_icpt = np.polyfit(ts, ms, 1)
        dark_current = float(d_slope) * k_e_per_dn
        black = float(d_icpt)
    else:
        dark_current, black = None, dmu0

    dsnu = et.emva1288_dsnu(darks[0][1], k_e_per_dn)
    unsat = [i for i in range(len(points)) if i < i_sat] or [0]
    i50 = min(unsat, key=lambda i: abs(mu[i] - 0.5 * mu_sat))
    t50 = points[i50]["exposure_s"]
    flat50 = flats[points[i50]["stack"]][2]
    prnu = et.emva1288_prnu(_nearest(darks, t50)[1], flat50)
    return {
        "K_e_per_DN": k_e_per_dn,
        "K_fit_intercept_dn2": float(intercept),
        "read_noise_e": read_e,
        "dsnu_e": dsnu.dsnu_e,
        "prnu_fraction": prnu.prnu_fraction,
        "dark_current_e_per_s": dark_current,
        "full_well_e": mu_sat * k_e_per_dn if saturated else None,
        "saturation_reached": saturated,
        "black_level_DN": black,
        "ptc": points,
        "n_frames": int(darks[0][1].shape[0]),
        "plane_shape": list(darks[0][1].shape[1:]),
    }


def simulate_emva_captures(
    rec: dict,
    darks: list[tuple[float, np.ndarray]],
    flats: list[tuple[float, float | None, np.ndarray]],
    measured: dict,
    seed: int = 0,
) -> tuple[list, list]:
    """Recipe-model stacks matching the measured exposures, levels and sizes.

    Flat signal is reproduced from ``relative_exposure`` (photons scale with it)
    using the photon scale implied by the unsaturated measured points and the
    recipe K; without it each level is matched to the measured mean (saturated
    levels then cannot be reproduced). The forward model is
    tools/emva_theory.simulate_uniform_stack -- the EMVA picture apply_emva_noise
    implements -- followed by rounding and clipping to the ADC range.
    """
    shape = darks[0][1].shape[1:]
    rng = np.random.default_rng(seed)
    prnu_map = 1.0 + rng.normal(0.0, rec["prnu_fraction"], size=shape)
    dsnu_map = rng.normal(0.0, rec["dsnu_e"], size=shape)
    max_dn = float(2 ** rec["bit_depth"] - 1)
    k = rec["K_e_per_DN"]

    def stack(mu_e: float, t: float, n: int, s: int) -> np.ndarray:
        dn = et.simulate_uniform_stack(
            mu_e=mu_e,
            n_frames=n,
            prnu_map=prnu_map,
            dsnu_map=dsnu_map,
            dark_mean_e=rec["dark_current_e_per_s"] * t,
            sigma_d_e=rec["read_noise_e"],
            K_e_per_DN=k,
            black_level_DN=rec["black_level_DN"],
            full_well_e=rec["full_well_e"],
            use_poisson=rec["use_poisson"],
            seed=s,
        )
        return np.clip(np.rint(dn), 0.0, max_dn)

    pts = measured["ptc"]
    mu_sat = max(p["mu_dn"] for p in pts if p["var_dn2"] == max(q["var_dn2"] for q in pts))
    ref = [p for p in pts if p["relative_exposure"] and 0 < p["mu_dn"] <= K_FIT_MAX_FRACTION_OF_SAT * mu_sat]
    photon_scale = float(np.median([p["mu_dn"] * k / p["relative_exposure"] for p in ref])) if ref else None

    sim_darks = [(t, stack(0.0, t, s.shape[0], seed + 1 + i)) for i, (t, s) in enumerate(darks)]
    sim_flats = []
    for i, (t, rel, s) in enumerate(flats):
        if rel is not None and photon_scale is not None:
            mu_e = photon_scale * float(rel)
        else:
            mu_e = max(_temporal(s)[0] - _nearest(darks, t)[1].mean(), 0.0) * k
        sim_flats.append((t, rel, stack(mu_e, t, s.shape[0], seed + 100 + i)))
    return sim_darks, sim_flats


EMVA_KEYS = ("K_e_per_DN", "read_noise_e", "dsnu_e", "prnu_fraction", "dark_current_e_per_s", "full_well_e")


def _rel(a: float | None, b: float | None) -> float | None:
    if a is None or b is None or b == 0:
        return None
    return 100.0 * (float(a) / float(b) - 1.0)


def emva_section(capture: Capture, rec: dict, seed: int) -> dict:
    cfg = capture.cfg["emva"]
    colour = str(cfg.get("plane", "G"))
    roi = cfg.get("roi")
    darks = [(float(e["exposure_s"]), capture.stack(e, roi, colour)) for e in cfg["darks"]]
    flats = [(float(e["exposure_s"]), e.get("relative_exposure"), capture.stack(e, roi, colour)) for e in cfg["flats"]]
    measured = analyse_emva(darks, flats)
    sim_d, sim_f = simulate_emva_captures(rec, darks, flats, measured, seed)
    simulated = analyse_emva(sim_d, sim_f)
    table = {
        k: {
            "measured": measured[k],
            "recipe": rec[k],
            "simulated": simulated[k],
            "measured_vs_recipe_pct": _rel(measured[k], rec[k]),
            "measured_vs_simulated_pct": _rel(measured[k], simulated[k]),
        }
        for k in (*EMVA_KEYS, "black_level_DN")
    }
    return {"plane": colour, "parameters": table, "measured": measured, "simulated": simulated}


# =====================================================================
# Running the production sensor chain (apply_emva_noise.py)
# =====================================================================
def run_sensor_chain(
    recipe: Path, electrons_rgb: np.ndarray, integration_time_s: float, seed: int, workdir: Path
) -> np.ndarray:
    """Push an ``(H, W, 3)`` electron image through tools/apply_emva_noise.py; return raw DN."""
    workdir.mkdir(parents=True, exist_ok=True)
    npz = workdir / f"electrons_{seed}.npz"
    raw = workdir / f"raw_{seed}.raw16"
    np.savez(npz, electrons_rgb=np.asarray(electrons_rgb, dtype=np.float32))
    cmd = [
        sys.executable,
        str(TOOLS / "apply_emva_noise.py"),
        "--repo-root",
        str(REPO),
        "--camera-model-config",
        str(recipe),
        "--electrons-npz",
        str(npz),
        "--seed",
        str(int(seed)),
        "--integration-time-s",
        repr(float(integration_time_s)),
        "--exposure-scale",
        "1.0",
        "--raw-out",
        str(raw),
        "--preview-white-balance-enabled",
        "false",
        "--preview-color-correction-enabled",
        "false",
    ]
    proc = subprocess.run(cmd, capture_output=True, text=True, check=False)
    if proc.returncode != 0:
        raise RuntimeError(f"apply_emva_noise failed:\n{proc.stdout}\n{proc.stderr}")
    h, w = electrons_rgb.shape[:2]
    return read_raw(raw, {"format": "raw16", "height": h, "width": w})[0]


