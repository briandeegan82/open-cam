def optics_mtf_2d(shape: tuple[int, int], model: dict, extra_sigma_px: float = 0.0) -> np.ndarray:
    """Recipe optics MTF on an FFT grid: diffraction at the working f-number
    (550 nm) times the recipe's post-PSF Gaussian when enabled, times an
    optional extra Gaussian blur. This is a lens-aberration-free model; supply
    ``slanted_edge.simulated_file`` (a pbrt render through the traced lens and
    apply_emva_noise) to compare against a full simulation instead."""
    fy = np.fft.fftfreq(shape[0])[:, None]
    fx = np.fft.fftfreq(shape[1])[None, :]
    fr = np.hypot(fx, fy)
    sensor, lens = model["sensor"], model.get("lens", {})
    n = effective_f_number(sensor, lens, tag="validate_against_capture")
    pitch = float(sensor.get("pixel_pitch_um", 1.4))
    h = sfr.diffraction_mtf(fr, n, 550.0, pitch)
    psf = lens.get("post_psf", {}) or {}
    sigma = float(psf.get("sigma_geometric_pixels", 0.0)) if psf.get("enabled") else 0.0
    sigma = math.hypot(sigma, float(extra_sigma_px))
    if sigma > 0:
        h = h * sfr.gaussian_mtf(fr, sigma)
    return h


def blur(img: np.ndarray, mtf2d_fn) -> np.ndarray:
    pad = 32
    p = np.pad(img, pad, mode="reflect")
    out = np.real(np.fft.ifft2(np.fft.fft2(p) * mtf2d_fn(p.shape)))
    return out[pad:-pad, pad:-pad]


def edge_plateaus(plane: np.ndarray) -> tuple[float, float]:
    fit = sfr.fit_edge(plane)
    rows, cols = np.mgrid[0 : plane.shape[0], 0 : plane.shape[1]].astype(float)
    d = (cols - fit.position(rows[:, 0])[:, None]) * fit.polarity
    m = max(4.0, plane.shape[1] / 6.0)
    return float(plane[d < -m].mean()), float(plane[d > m].mean())


def measure_edge(img: np.ndarray, pattern: str | None, colour: str, flatfield: bool) -> dict:
    plane = cfa_plane(img, pattern, colour)
    step = 2.0 if pattern else 1.0
    r = sfr.slanted_edge_sfr(plane, flatfield=flatfield)
    edge = sfr.fit_edge(plane)
    return {
        "angle_deg": r.angle_deg,
        "polarity": edge.polarity,
        "frequency_cy_per_px": (r.frequency_cy_per_px / step).tolist(),
        "mtf": r.mtf.tolist(),
        "mtf50_cy_per_px": r.mtf50_cy_per_px / step,
        "plane_nyquist_cy_per_px": 0.5 / step,
    }


def synthetic_edge_unit(h: int, w: int, angle_deg: float, polarity: int) -> np.ndarray:
    e = sfr.synthetic_slanted_edge(h, w, angle_deg, dark=0.0, bright=1.0)
    if sfr.fit_edge(e).polarity != polarity:
        e = sfr.synthetic_slanted_edge(h, w, -angle_deg, dark=0.0, bright=1.0)[:, ::-1]
    return e


def slanted_edge_section(
    capture: Capture, recipe: Path, model: dict, rec: dict, emva: dict | None, seed: int, workdir: Path
) -> dict:
    cfg = capture.cfg["slanted_edge"]
    colour = str(cfg.get("plane", "G"))
    flat = bool(cfg.get("flatfield", False))
    black = emva["measured"]["black_level_DN"] if emva else capture.raw.get("black_level_DN", rec["black_level_DN"])
    img, meta = read_raw(capture.root / cfg["file"], capture.fmt(cfg))
    img = crop(img, cfg.get("roi")) - meta.get("black_level_DN", black)
    measured = measure_edge(img, capture.pattern, colour, flat)

    sim_pattern = model["cfa"].get("pattern") if model["cfa"].get("enabled") else None
    if cfg.get("simulated_file"):
        sim_img, _ = read_raw(capture.root / cfg["simulated_file"], capture.fmt(cfg))
        sim_img = crop(sim_img, cfg.get("roi")) - rec["black_level_DN"]
        source = "simulated_file"
    else:
        unit = synthetic_edge_unit(img.shape[0], img.shape[1], measured["angle_deg"], measured["polarity"])
        unit = blur(unit, lambda s: optics_mtf_2d(s, model))
        k = rec["K_e_per_DN"]
        levels = [edge_plateaus(cfa_plane(img, capture.pattern, c)) for c in "RGB"]
        e = np.stack([(lo + (hi - lo) * unit) * k for lo, hi in levels], axis=-1)
        sim_img = run_sensor_chain(recipe, np.clip(e, 0, None), float(cfg.get("exposure_s", 0.01)), seed, workdir)
        sim_img = sim_img - rec["black_level_DN"]
        source = "recipe_optics_model"
    simulated = measure_edge(sim_img, sim_pattern, colour, flat)
    f = np.asarray(measured["frequency_cy_per_px"])
    keep = f <= measured["plane_nyquist_cy_per_px"]
    sim_on = np.interp(f[keep], simulated["frequency_cy_per_px"], simulated["mtf"])
    pitch = float(model["sensor"].get("pixel_pitch_um", 1.4))
    out = {
        "plane": colour,
        "simulation": source,
        "measured": measured,
        "simulated": simulated,
        "mtf50_measured_cy_per_px": measured["mtf50_cy_per_px"],
        "mtf50_simulated_cy_per_px": simulated["mtf50_cy_per_px"],
        "mtf50_measured_lp_per_mm": sfr.cycles_per_mm(measured["mtf50_cy_per_px"], pitch),
        "mtf50_simulated_lp_per_mm": sfr.cycles_per_mm(simulated["mtf50_cy_per_px"], pitch),
        "mtf50_measured_vs_simulated_pct": _rel(measured["mtf50_cy_per_px"], simulated["mtf50_cy_per_px"]),
        "mtf_rms_difference_to_plane_nyquist": float(
            np.sqrt(np.mean((np.asarray(measured["mtf"])[keep] - sim_on) ** 2))
        ),
    }
    for fq in (0.1, 0.2):
        out[f"mtf_at_{fq}_cy_per_px"] = {
            "measured": float(np.interp(fq, f, measured["mtf"])),
            "simulated": float(np.interp(fq, simulated["frequency_cy_per_px"], simulated["mtf"])),
        }
    return out


