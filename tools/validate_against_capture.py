        ax2 = axes[1].twinx()
        ax2.plot(x, [p["delta_e_2000"] for p in pts], "k.-", lw=0.8)
        ax2.set_ylabel("$\\Delta E_{00}$")
        axes[1].set_xlabel("patch")
