from opencam_gui.core import pipeline as pl
from opencam_gui.core.catalog import find_recipe, list_illuminants
from opencam_gui.core.repo import pbrt_available, repo_root

TERMINAL_STATES = frozenset({"succeeded", "failed", "cancelled", "interrupted"})


@dataclass
class RunRequest:
    scene_id: str
    camera_id: str
    mode: str = "fast_analytic"  # "fast_analytic" | "pbrt_accurate"
    illuminant_id: str | None = "D65"
    target_illuminance_lux: float = 500.0
    exposure_time_s: float | None = None
    seed: int = 0
    xres: int = 480
    yres: int = 320
    pixelsamples: int = 64
    name: str = ""

    @classmethod
    def from_dict(cls, d: dict) -> RunRequest:
        known = {k: d[k] for k in cls.__dataclass_fields__ if k in d}
        return cls(**known)

    def validate(self) -> None:
        if self.scene_id not in pl.SCENES:
            raise ValueError(f"unknown scene: {self.scene_id!r}")
        find_recipe(self.camera_id)  # raises KeyError
        scene = pl.SCENES[self.scene_id]
        if self.mode not in ("fast_analytic", "pbrt_accurate"):
            raise ValueError(f"unknown mode: {self.mode!r}")
        if self.mode == "fast_analytic" and not scene.supports_fast_analytic:
            raise ValueError(f"{scene.label} needs a PBRT render (mode 'pbrt_accurate')")
        if self.illuminant_id and self.illuminant_id not in {i.id for i in list_illuminants()}:
            raise ValueError(f"unknown illuminant: {self.illuminant_id!r}")
        if not 0 < self.target_illuminance_lux <= 1e6:
            raise ValueError("target_illuminance_lux must be in (0, 1e6]")
        if self.exposure_time_s is not None and not 0 < self.exposure_time_s <= 60:
            raise ValueError("exposure_time_s must be in (0, 60] s")
        if not (16 <= self.xres <= 8192 and 16 <= self.yres <= 8192):
            raise ValueError("resolution must be 16..8192 px per side")
        if not 1 <= self.pixelsamples <= 1 << 16:
            raise ValueError("pixelsamples must be 1..65536")


def _illuminant_path(illuminant_id: str | None) -> str | None:
    if not illuminant_id:
        return None
    for i in list_illuminants():
        if i.id == illuminant_id:
            return i.repo_relative
    raise ValueError(f"unknown illuminant: {illuminant_id!r}")


def generation_request(req: RunRequest, run_label: str) -> pl.GenerationRequest:
    scene = pl.SCENES[req.scene_id]
    return pl.GenerationRequest(
        scene_id=req.scene_id,
        camera_model_config=find_recipe(req.camera_id).path,
        mode=req.mode,
        illuminant_csv=_illuminant_path(req.illuminant_id) if scene.supports_illuminant_spectrum else None,
        target_illuminance_lux=float(req.target_illuminance_lux),
        exposure_time_s=req.exposure_time_s,
        seed=int(req.seed),
        xres=int(req.xres),
        yres=int(req.yres),
        pixelsamples=int(req.pixelsamples),
        run_label=run_label,
    )


def plan_steps(req: RunRequest, run_label: str = "studio_preview") -> list[pl.Step]:
    req.validate()
    return pl.build_plan(generation_request(req, run_label))


def shell_script(steps: list[pl.Step]) -> str:
    lines = [
        "#!/usr/bin/env bash",
        "# Generated by Open Cam Studio. Re-runs this simulation without the GUI.",
        "set -euo pipefail",
        f"cd {shlex.quote(str(repo_root()))}",
        "",
    ]
    for s in steps:
        lines.append(f"# {s.name}")
        lines.append(shlex.join(s.argv))
        lines.append("")
    return "\n".join(lines)


# --------------------------------------------------------------------------- run store


@dataclass
class StepRecord:
    name: str
    argv: list[str]
    returncode: int | None = None
    started: float | None = None
    finished: float | None = None


@dataclass
class RunRecord:
    id: str
    request: dict
    status: str = "queued"
    created: float = field(default_factory=time.time)
    started: float | None = None
    finished: float | None = None
    error: str | None = None
    steps: list[StepRecord] = field(default_factory=list)
    outputs: list[str] = field(default_factory=list)

    def to_dict(self) -> dict:
        return asdict(self)

    @classmethod
    def from_dict(cls, d: dict) -> RunRecord:
        steps = [StepRecord(**s) for s in d.get("steps", [])]
        fields = {k: d[k] for k in cls.__dataclass_fields__ if k in d and k != "steps"}
        return cls(steps=steps, **fields)


def default_runs_dir() -> Path:
    env = os.environ.get("OPENCAM_STUDIO_RUNS")
    return Path(env).resolve() if env else repo_root() / "out" / "studio_runs"


_SLUG = re.compile(r"[^a-z0-9]+")


def _slug(text: str) -> str:
    return _SLUG.sub("-", text.lower()).strip("-")[:40]


class RunStore:
    def __init__(self, root: Path | None = None) -> None:
        self.root = (root or default_runs_dir()).resolve()
        self.root.mkdir(parents=True, exist_ok=True)
        self._lock = threading.Lock()

    def run_dir(self, run_id: str) -> Path:
        if not run_id or "/" in run_id or run_id.startswith("."):
            raise KeyError(run_id)
        return self.root / run_id

    def new_id(self, req: RunRequest) -> str:
        stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
        base = "-".join(p for p in (stamp, _slug(req.name) or _slug(req.scene_id), _slug(req.camera_id)) if p)
        run_id, n = base, 1
        while (self.root / run_id).exists():
            n += 1
            run_id = f"{base}-{n}"
        return run_id

    def save(self, rec: RunRecord) -> None:
        d = self.run_dir(rec.id)
        d.mkdir(parents=True, exist_ok=True)
        tmp = d / "run.json.tmp"
        with self._lock:
            tmp.write_text(json.dumps(rec.to_dict(), indent=2))
            tmp.replace(d / "run.json")

    def load(self, run_id: str) -> RunRecord:
        p = self.run_dir(run_id) / "run.json"
        if not p.is_file():
            raise KeyError(run_id)
        return RunRecord.from_dict(json.loads(p.read_text()))

    def list(self) -> list[RunRecord]:
        out = []
        for p in self.root.glob("*/run.json"):
            try:
                out.append(RunRecord.from_dict(json.loads(p.read_text())))
            except (OSError, ValueError, TypeError):
                continue
        return sorted(out, key=lambda r: r.created, reverse=True)

    def delete(self, run_id: str) -> None:
        d = self.run_dir(run_id)
        if not (d / "run.json").is_file():
            raise KeyError(run_id)
        shutil.rmtree(d)

    def log_path(self, run_id: str) -> Path:
        return self.run_dir(run_id) / "log.txt"

    def mark_interrupted(self) -> None:
        """Runs left queued/running by a previous server process can never finish."""
        for rec in self.list():
            if rec.status not in TERMINAL_STATES:
                rec.status = "interrupted"
                rec.error = rec.error or "Studio server stopped before this run finished."
                rec.finished = rec.finished or time.time()
                self.save(rec)


# --------------------------------------------------------------------------- outputs


def _output_sources(req: RunRequest, run_id: str) -> list[tuple[Path, str]]:
    """(tool output path, name inside outputs/) pairs written by the plan for this scene."""
    out = repo_root() / "out"
    scene = pl.SCENES[req.scene_id]
    srcs: list[tuple[Path, str]] = [(out / "colorchecker_noisy.raw16", "noisy.raw16")]
    if scene.kind == "colorchecker":
        srcs += [
            (out / "sensor_forward_electrons.npz", "electrons.npz"),
            (out / "colorchecker_spectral.exr", "spectral.exr"),
        ]
        srcs += [(p, p.name) for p in sorted(out.glob(f"run_{run_id}_*.json"))]
    else:
        target = scene.iq_target
        srcs += [
            (out / "iq_targets" / f"{target}_electrons.npz", "electrons.npz"),
            (out / f"{target}_spectral.exr", "spectral.exr"),
        ]
    return srcs


def collect_outputs(req: RunRequest, run_id: str, dest: Path, since: float) -> list[str]:
    """Copy this run's fresh tool outputs (mtime >= ``since``) into ``dest``; return relative names."""
    dest.mkdir(parents=True, exist_ok=True)
    collected: list[str] = []
    preview = pl.preview_output_dir()
    fresh = [p for p in sorted(preview.glob("*")) if p.is_file() and p.stat().st_mtime >= since - 1]
    if fresh:
        (dest / "preview").mkdir(exist_ok=True)
        for p in fresh:
            shutil.copy2(p, dest / "preview" / p.name)
            collected.append(f"preview/{p.name}")
    for src, name in _output_sources(req, run_id):
        if src.is_file() and src.stat().st_mtime >= since - 1:
            shutil.copy2(src, dest / name)
            collected.append(name)
    return collected


# --------------------------------------------------------------------------- job queue


class JobManager:
    """Runs queued runs one at a time on a background thread."""

    def __init__(self, store: RunStore) -> None:
        self.store = store
        self._queue: queue.Queue[str] = queue.Queue()
        self._cancelled: set[str] = set()
        self._current: tuple[str, subprocess.Popen] | None = None
        self._lock = threading.Lock()
        self._thread: threading.Thread | None = None

    # ---- public API

    def start(self) -> None:
        if self._thread is None:
            self._thread = threading.Thread(target=self._worker, name="opencam-studio-jobs", daemon=True)
            self._thread.start()

    def submit(self, req: RunRequest) -> RunRecord:
        req.validate()
        if req.mode == "pbrt_accurate" and not pbrt_available():
            raise ValueError(
                "PBRT is not built (third_party/pbrt-v4/build/pbrt). Build it with tools/build_pbrt.sh "
                "or use the fast analytic mode for the ColorChecker."
            )
        run_id = self.store.new_id(req)
        rec = RunRecord(id=run_id, request=asdict(req))
        d = self.store.run_dir(run_id)
        d.mkdir(parents=True)
        (d / "request.json").write_text(json.dumps(asdict(req), indent=2))
        self.store.save(rec)
        self._queue.put(run_id)
        return rec

    def cancel(self, run_id: str) -> RunRecord:
        rec = self.store.load(run_id)
        if rec.status in TERMINAL_STATES:
            return rec
        with self._lock:
            self._cancelled.add(run_id)
            current = self._current
        if current and current[0] == run_id:
            _terminate(current[1])
        elif rec.status == "queued":
            rec.status, rec.finished = "cancelled", time.time()
            self.store.save(rec)
        return self.store.load(run_id)

    def queue_position(self, run_id: str) -> int | None:
        with self._queue.mutex:
            items = list(self._queue.queue)
        return items.index(run_id) + 1 if run_id in items else None

    # ---- execution

    def _worker(self) -> None:
        while True:
            run_id = self._queue.get()
            try:
                self.execute(run_id)
            except Exception as exc:  # keep the worker alive whatever a run does
                try:
                    rec = self.store.load(run_id)
                    rec.status, rec.error, rec.finished = "failed", f"internal error: {exc}", time.time()
                    self.store.save(rec)
                except KeyError:
                    pass
            finally:
                self._queue.task_done()

    def execute(self, run_id: str, echo: bool = False) -> RunRecord:
        rec = self.store.load(run_id)
        if rec.status != "queued" or run_id in self._cancelled:
            if rec.status == "queued":
                rec.status, rec.finished = "cancelled", time.time()
                self.store.save(rec)
            return rec
        req = RunRequest.from_dict(rec.request)
        d = self.store.run_dir(run_id)
        log = self.store.log_path(run_id)

        steps = plan_steps(req, run_label=run_id)
        steps = _localise_pipeline_yaml(steps, d)
        (d / "run.sh").write_text(shell_script(steps))
        (d / "run.sh").chmod(0o755)
        rec.steps = [StepRecord(name=s.name, argv=s.argv) for s in steps]
        rec.status, rec.started = "running", time.time()
        self.store.save(rec)

        with log.open("a", buffering=1) as fh:

            def emit(line: str) -> None:
                fh.write(line + "\n")
                if echo:
                    print(line, flush=True)

            for i, step in enumerate(steps):
                srec = rec.steps[i]
                srec.started = time.time()
                self.store.save(rec)
                emit(f"=== [{i + 1}/{len(steps)}] {step.name}")
                emit("$ " + shlex.join(step.argv))
                srec.returncode = self._run_step(run_id, step, emit)
                srec.finished = time.time()
                self.store.save(rec)
                if run_id in self._cancelled:
                    rec.status, rec.error = "cancelled", "Cancelled by user."
                    break
                if srec.returncode != 0:
                    rec.status, rec.error = "failed", f"{step.name} failed (exit {srec.returncode})"
                    break
            else:
                rec.status = "succeeded"
            rec.outputs = collect_outputs(req, run_id, d / "outputs", since=rec.started)
            rec.finished = time.time()
            emit(f"=== {rec.status} in {rec.finished - rec.started:.1f} s")
        self.store.save(rec)
        return rec

    def _run_step(self, run_id: str, step: pl.Step, emit) -> int:
        try:
            proc = subprocess.Popen(
                step.argv,
                cwd=str(repo_root()),
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                text=True,
                bufsize=1,
                env={**os.environ, "PYTHONUNBUFFERED": "1"},
                start_new_session=True,
            )
        except OSError as exc:
            emit(f"error: {exc}")
            return 127
        with self._lock:
            self._current = (run_id, proc)
            cancelled = run_id in self._cancelled
        if cancelled:
            _terminate(proc)
        assert proc.stdout is not None
        with proc.stdout:
            for line in proc.stdout:
                emit(line.rstrip("\r\n"))
        rc = proc.wait()
        with self._lock:
            self._current = None
        return rc


def _terminate(proc: subprocess.Popen) -> None:
    """Stop a step and its children (pbrt is launched by run_pipeline.py)."""
    try:
        os.killpg(proc.pid, signal.SIGTERM)
    except (ProcessLookupError, PermissionError):
        return

    def _kill_later() -> None:
        try:
            proc.wait(timeout=5)
        except subprocess.TimeoutExpired:
            with contextlib.suppress(ProcessLookupError, PermissionError):
                os.killpg(proc.pid, signal.SIGKILL)

    threading.Thread(target=_kill_later, daemon=True).start()


def _localise_pipeline_yaml(steps: list[pl.Step], run_dir: Path) -> list[pl.Step]:
    """Copy a generated ``out/gui_runs/<id>/pipeline.yaml`` into the run dir and point argv at it."""
    out: list[pl.Step] = []
    for s in steps:
        argv = list(s.argv)
        if "--config" in argv:
            i = argv.index("--config") + 1
            src = Path(argv[i])
            if src.is_file() and src.name == "pipeline.yaml":
                dst = run_dir / "pipeline.yaml"
                shutil.copy2(src, dst)
                argv[i] = str(dst)
        out.append(pl.Step(s.name, argv))
    return out
