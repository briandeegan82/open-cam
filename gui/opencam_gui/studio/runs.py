"""Run records and the background job queue behind Open Cam Studio.

A run is one :class:`RunRequest` turned into the same ``tools/*.py`` command plan the
Image Generation demo uses (:func:`opencam_gui.core.pipeline.build_plan`). Each run gets a
directory::

    <runs_dir>/<run_id>/
        request.json   # the GUI settings; reload or re-run them with ``opencam-studio run``
        run.json       # status, timings, per-step exit codes, collected outputs
        run.sh         # the exact commands, runnable without the GUI
        pipeline.yaml  # (PBRT ColorChecker only) the generated tools/run_pipeline.py config
        log.txt        # combined stdout/stderr of every step
        outputs/       # copies of the PNG previews, RAW16, electrons NPZ, spectral EXR, stats

The tools write to fixed paths under ``out/``, so the queue runs one job at a time and copies
the results into the run directory when a job finishes.
"""

from __future__ import annotations

import contextlib
import json
import os
import queue
import re
